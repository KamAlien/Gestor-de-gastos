%=========================================================================================================================================================================================================
% CLASSIFCATION HELPERS: CLEAN THE TEXT, SPLIT IT INTO WORDS AND LOOK FOR A HINT
%=========================================================================================================================================================================================================
:- encoding(utf8).

remove_accent(Char, Plain):-
    (   sub_atom('áéíóúüñ', I, 1, _, Char)
    ->  sub_atom('aeiouun', I, 1, _, Plain)
    ;   Plain = Char
    ).

remove_accents(Text, Clean):-
    string_lower(Text, Lowercase),
    string_chars(Lowercase, Chars),
    maplist(remove_accent, Chars, Plain),
    string_chars(Clean, Plain).

%=========================================================================================================================================================================================================
% NORMALIZE: NO ACCENTS, LOWERCASE AND NO EXTRA SPACES
%=========================================================================================================================================================================================================
normalize_text(Text, Normal):-
    remove_accents(Text, Clean),
    normalize_space(string(Normal), Clean).

%=========================================================================================================================================================================================================
% SPLIT A TEXT INTO WORDS (by spaces and punctuation marks)
%=========================================================================================================================================================================================================
words_of(Text, Words):-
    remove_accents(Text, Clean),
    split_string(Clean, " ,.;:!?()-/", " ,.;:!?()-/", All),
    exclude(==(""), All, Words).

%=========================================================================================================================================================================================================
% THE HINT IS ONE OF THE WORDS (or its plural: zapato -> zapatos, doctor -> doctores)
%=========================================================================================================================================================================================================

hint_in_words(Hint, Words):-
    normalize_text(Hint, Normal),
    Normal \== "",
    member(Word, Words),
    word_matches(Normal, Word),
    !.

word_matches(Hint, Hint).
word_matches(Hint, Word):- string_concat(Hint, "s", Word).
word_matches(Hint, Word):- string_concat(Hint, "es", Word).