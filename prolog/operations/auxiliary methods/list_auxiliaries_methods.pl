%====================================================================================================
% DEVUELVE EL LA LISTA SIN EL PRIMER ELEMENTO Y LO DEVUELVE
%====================================================================================================
pop(L, R, X):-
    L = [First_element | Rest],
    R = Rest,
    X = First_element.

%====================================================================================================
% SE LE AGREGA UN ELEMENTO AL INICIO DE LA LISTA
%====================================================================================================

push(X, L, R):-
    R = [X | L].

%====================================================================================================
% SE LE AGREGA UN ELEMENTO AL FINAL DE UNA LISTA
add(X, L, R):-
    concatenar(L, [X], R).

%====================================================================================================
% UNE 2 LISTAS
%====================================================================================================
concatenar([], L, L).
concatenar([X | L1], L2, [X | R]):- concatenar(L1, L2, R).
